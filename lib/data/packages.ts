export function getPackageBySlug(slug: string) {
  return tourPackages.find((p) => p.slug === slug);
}

export function getPackagesByCategory(category?: string) {
  if (!category) return tourPackages;
  return tourPackages.filter((p) => p.category === category);
}

export function getFeaturedPackages() {
  return tourPackages.filter((p) => p.featured);
}

export function getRelatedPackages(pkg: TourPackage, limit = 3) {
  return tourPackages
    .filter((p) => p.slug !== pkg.slug && p.category === pkg.category)
    .slice(0, limit);
}
